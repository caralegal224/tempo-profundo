const { chromium } = require('playwright');
const path = require('path'); const fs = require('fs');
(async () => {
  const b = await chromium.launch({ args: ['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--autoplay-policy=no-user-gesture-required'] });
  const p = await b.newPage({ viewport: { width: 1440, height: 880 }, deviceScaleFactor: 1 });
  const errs = [];
  p.on('console', m => { if (m.type() === 'error' || m.type()==='warning') errs.push(m.type()+': '+m.text()); });
  p.on('pageerror', e => errs.push('pageerror: ' + e.message));
  await p.route('**/three.min.js', r => r.fulfill({ path: path.resolve('node_modules/three/build/three.min.js'), contentType: 'application/javascript' }));
  await p.route('https://fonts.googleapis.com/**', r => r.fulfill({ body: '', contentType: 'text/css' }));
  await p.goto('file://' + path.resolve('dist/play.html'));
  await p.waitForTimeout(3000);
  const out = process.argv[2] || '/tmp/claude-0/shots';
  fs.mkdirSync(out, { recursive: true });
  await p.screenshot({ path: out + '/01-genesis.png' });
  await p.click('#g-start');
  await p.waitForTimeout(800);
  // semear no centro de um oceano raso
  const uv = await p.evaluate(() => { const w = app.world; for (let t=0;t<9000;t++){ const x=Math.floor(Math.random()*160), y=25+Math.floor(Math.random()*30); const i=y*160+x; if(!w.land[i]&&w.depth[i]<0.12) return [(x+.5)/160,(y+.5)/80]; } return [0.5,0.5]; });
  await p.evaluate(([u,v]) => { app.map.cx = u; app.map.cy = v; app.map.clampView(); }, uv);
  const sc = await p.evaluate(([u,v]) => app.map.toScreen(u,v), uv);
  await p.mouse.click(sc[0], sc[1]);
  await p.evaluate(() => { app.setSpeed(5); app.closeDrawer(); const w=app.world; const v=w.vents[0]; w.seed(app.creator.g.slice? Float32Array.from(app.creator.g):app.creator.g, v.x, v.y, 10); });
  await p.waitForTimeout(9000);
  await p.screenshot({ path: out + '/02-map.png' });
  await p.evaluate(() => { const w=app.world; let i=-1; for(let k=0;k<4200;k++) if(w.alive[k]){i=k;break;} if(i>=0) app.selectAgent(i); app.map.zoom=6; app.map.cx=w.ax[i]/160; app.map.cy=w.ay[i]/80; app.map.clampView(); });
  await p.waitForTimeout(1500);
  await p.screenshot({ path: out + '/03-inspect.png' });
  await p.evaluate(() => { app.setView('3d'); });
  await p.waitForTimeout(2500);
  await p.screenshot({ path: out + '/04-3d.png' });
  await p.evaluate(() => { app.v3.targetDist = 1.12; app.follow = true; });
  await p.waitForTimeout(4000);
  await p.screenshot({ path: out + '/05-3dclose.png' });
  await p.evaluate(() => { app.setView('2d'); app.deselect(); app.openAtlas(); });
  await p.waitForTimeout(1000);
  await p.screenshot({ path: out + '/06-atlas.png' });
  console.log(await p.evaluate(() => { const t0=performance.now(); for(let k=0;k<5;k++) app.painter.compose(); const tc=(performance.now()-t0)/5; const t1=performance.now(); for(let k=0;k<20;k++) app.world.step(); return 'compose ms '+tc.toFixed(1)+' step ms '+((performance.now()-t1)/20).toFixed(2); }));
  console.log(await p.evaluate(() => JSON.stringify({ n: app.world.count, sp: app.world.living, years: app.world.years, steps: app.world.stepN })));
  console.log(errs.slice(0, 20).join('\n'));
  await b.close();
})();
